import { emptyBook, bindIdentity, accountEnergy, earnMerit, close, sellMerit, tradeEfuse, mint, report } from "../edge/trilogy.js";
let book = emptyBook();
const id = bindIdentity(book, "seat:a", "evidence:1");
if (!id.ok) process.exit(1);
book = id.book;
const en = accountEnergy(book, "seat:a", 10);
if (!en.ok) process.exit(1);
book = en.book;
const m = earnMerit(book, "seat:a", "work:closed");
if (!m.ok || m.book.seats["seat:a"].merit !== 1) process.exit(1);
book = m.book;
const c = close(book, "seat:a");
if (!c.ok || c.order !== 0) process.exit(1);
book = c.book;
if (sellMerit().ok || tradeEfuse().ok || mint().ok) process.exit(1);
const noId = earnMerit(emptyBook(), "seat:b", "x");
if (noId.ok) process.exit(1);
console.log(JSON.stringify(report(book), null, 2));
