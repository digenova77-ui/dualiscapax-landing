TEXT_FILES = ["index.html", "world.html", "README.md", "BINDING-PLAN.md",
              "LICENSE", "manifest.json", "menu-manifest.json"]
BANNED = ["Emergent", "Grok", "Claude", "Meta", "David",
          "Di Genova", "DiGenova", "Di-Genova", "©"]


def scan():
    counts = {t: 0 for t in BANNED}
    meta_syntax = 0
    dualis = {}
    domains = {}
    for rel in TEXT_FILES:
        text = (PKG / rel).read_text(encoding="utf-8")
        dualis[rel] = text.count("DualisCapax")
        domains[rel] = text.count("dualiscapax.ai") + text.count("dualiscapax.com")
        for term in BANNED:
            hits = len(re.findall(re.escape(term), text, flags=re.IGNORECASE))
            if term == "Meta":
                meta_syntax += len(re.findall(r"<meta[\s>]", text))
                hits -= len(re.findall(r"<meta[\s>]", text))
            counts[term] += hits
    return counts, meta_syntax, dualis, domains


def hrefs(rel):
    text = (PKG / rel).read_text(encoding="utf-8")
    return sorted(set(re.findall(r'href="([^"]+)"', text)))


