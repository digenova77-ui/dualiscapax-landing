export const COM_IDENTITY_ORIGIN = "https://dualiscapax.com";
export const AI_HANDOFF_ACTION = "https://dualiscapax.ai/auth/consume";
const AI_RECEIVER_ORIGIN = "https://dualiscapax.ai";
const PRODUCTION_RP_ID = "dualiscapax.com";
const PRODUCTION_IDENTITY_CONFIG = Object.freeze({
  mode: "production",
  frontendOrigin: COM_IDENTITY_ORIGIN,
  identityIssuerOrigin: COM_IDENTITY_ORIGIN,
  receiverOrigin: "https://dualiscapax.ai",
  webauthnRpId: "dualiscapax.com",
  handoffProofVersion: 2,
});

const API_PATHS = Object.freeze({
  registrationOptions: "/auth/register/options",
  registrationVerify: "/auth/register/verify",
  assertionOptions: "/auth/assertion/options",
  assertionVerify: "/auth/assertion/verify",
});

function isTopLevelWindow() {
  try {
    const windowRef = globalThis.window;
    return Boolean(windowRef) && windowRef.top === windowRef;
  } catch {
    return false;
  }
}

function requireTopLevelWindow() {
  if (!isTopLevelWindow()) {
    throw new Error("Passkey identity requires a top-level window.");
  }
}

function base64UrlToBytes(value) {
  if (typeof value !== "string" || !/^[A-Za-z0-9_-]+$/.test(value)) {
    throw new Error("Invalid WebAuthn binary field.");
  }
  const base64 = value.replace(/-/g, "+").replace(/_/g, "/")
    .padEnd(Math.ceil(value.length / 4) * 4, "=");
  const binary = globalThis.atob(base64);
  return Uint8Array.from(binary, (character) => character.charCodeAt(0));
}

function bytesToBase64Url(buffer) {
  const bytes = new Uint8Array(buffer);
  let binary = "";
  for (let offset = 0; offset < bytes.length; offset += 0x8000) {
    binary += String.fromCharCode(...bytes.subarray(offset, offset + 0x8000));
  }
  return globalThis.btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/g, "");
}

function publicKeyOptionsFromServer(options, expectedRpId) {
  if (!options || typeof options !== "object" || typeof options.challenge !== "string") {
    throw new Error("The identity service returned invalid passkey options.");
  }
  if (
    expectedRpId &&
    (
      (options.rpId !== undefined && options.rpId !== expectedRpId) ||
      (options.rp?.id !== undefined && options.rp.id !== expectedRpId) ||
      (options.rpId === undefined && options.rp?.id === undefined)
    )
  ) throw new Error("The identity service returned an unexpected passkey relying party.");
  const verificationRequirements = [
    options.userVerification,
    options.authenticatorSelection?.userVerification,
  ].filter((value) => value !== undefined);
  if (
    verificationRequirements.length === 0 ||
    verificationRequirements.some((value) => value !== "required")
  ) throw new Error("The identity service did not require passkey user verification.");
  const publicKey = { ...options, challenge: base64UrlToBytes(options.challenge) };
  if (options.user) {
    if (typeof options.user.id !== "string") throw new Error("Invalid passkey user options.");
    publicKey.user = { ...options.user, id: base64UrlToBytes(options.user.id) };
  }
  if (Array.isArray(options.allowCredentials)) {
    publicKey.allowCredentials = options.allowCredentials.map((entry) => ({
      ...entry,
      id: base64UrlToBytes(entry.id),
    }));
  }
  return publicKey;
}

export function serializeWebAuthnCredential(credential) {
  if (!credential || credential.type !== "public-key" || !credential.response) {
    throw new Error("A passkey credential is required.");
  }
  const response = { clientDataJSON: bytesToBase64Url(credential.response.clientDataJSON) };
  for (const field of ["attestationObject", "authenticatorData", "signature"]) {
    const value = credential.response[field];
    if (value !== undefined && value !== null) {
      response[field] = bytesToBase64Url(value);
    }
  }
  const serialized = {
    id: credential.id,
    rawId: bytesToBase64Url(credential.rawId),
    type: credential.type,
    response,
  };
  return serialized;
}

function validateHandoff(handoff) {
  if (
    typeof handoff !== "string" ||
    handoff.length > 2048 ||
    !/^[A-Za-z0-9._-]+$/.test(handoff)
  ) {
    throw new Error("The identity service did not return a valid handoff.");
  }
  return handoff;
}

export function submitHandoffByPost(
  handoff,
  documentRef = globalThis.document,
  handoffAction = AI_HANDOFF_ACTION,
) {
  requireTopLevelWindow();
  const token = validateHandoff(handoff);
  if (!documentRef?.createElement || !documentRef.body) {
    throw new Error("The identity handoff cannot be submitted in this document.");
  }
  const action = new URL(handoffAction);
  if (
    action.protocol !== "https:" ||
    action.search ||
    action.hash ||
    action.pathname !== "/auth/consume" ||
    handoffAction !== `${action.origin}/auth/consume`
  ) {
    throw new Error("The identity handoff destination is invalid.");
  }
  const form = documentRef.createElement("form");
  form.method = "post";
  form.action = action.toString();
  form.enctype = "application/x-www-form-urlencoded";
  form.hidden = true;
  const input = documentRef.createElement("input");
  input.type = "hidden";
  input.name = "handoff";
  input.value = token;
  form.appendChild(input);
  documentRef.body.appendChild(form);
  form.submit();
}

export function createIdentityGateClient({
  fetchImpl = globalThis.fetch,
  credentialsApi = globalThis.navigator?.credentials,
  origin = globalThis.location?.origin,
  identityConfig = PRODUCTION_IDENTITY_CONFIG,
  submitHandoff = submitHandoffByPost,
} = {}) {
  requireTopLevelWindow();
  const issuer = new URL(identityConfig?.identityIssuerOrigin || "invalid:");
  const receiver = new URL(identityConfig?.receiverOrigin || "invalid:");
  const rpId = identityConfig?.webauthnRpId;
  const invalidProductionConfig = identityConfig?.mode === "production" && (
    origin !== COM_IDENTITY_ORIGIN ||
    identityConfig.frontendOrigin !== COM_IDENTITY_ORIGIN ||
    identityConfig.identityIssuerOrigin !== COM_IDENTITY_ORIGIN ||
    identityConfig.receiverOrigin !== AI_RECEIVER_ORIGIN ||
    rpId !== PRODUCTION_RP_ID
  );
  if (
    !["production", "staging"].includes(identityConfig?.mode) ||
    invalidProductionConfig ||
    identityConfig.frontendOrigin !== origin ||
    identityConfig.identityIssuerOrigin !== origin ||
    issuer.protocol !== "https:" ||
    receiver.protocol !== "https:" ||
    receiver.origin === origin ||
    typeof rpId !== "string" ||
    identityConfig.handoffProofVersion !== 2 ||
    !(issuer.hostname === rpId || issuer.hostname.endsWith(`.${rpId}`))
  ) throw new Error("Passkey identity configuration is invalid for this origin.");
  if (typeof fetchImpl !== "function") throw new Error("The identity service is unavailable.");
  if (!credentialsApi) throw new Error("Passkeys are unavailable in this browser.");

  async function post(path, body, signal) {
    if (!Object.values(API_PATHS).includes(path)) throw new Error("Unknown identity route.");
    const url = new URL(path, origin);
    if (url.origin !== origin || url.search || url.hash) throw new Error("Invalid identity route.");
    const response = await fetchImpl(path, {
      method: "POST",
      credentials: "same-origin",
      cache: "no-store",
      redirect: "error",
      headers: {
        accept: "application/json",
        "content-type": "application/json",
      },
      body: JSON.stringify(body),
      signal,
    });
    let result;
    try {
      result = await response.json();
    } catch {
      throw new Error("The identity service returned an invalid response.");
    }
    if (!response.ok || result?.ok !== true) {
      throw new Error("The identity service did not grant access.");
    }
    return result;
  }

  async function register({ signal } = {}) {
    requireTopLevelWindow();
    if (typeof credentialsApi.create !== "function") throw new Error("Passkey enrollment is unavailable.");
    const options = await post(API_PATHS.registrationOptions, {}, signal);
    const credential = await credentialsApi.create({
      publicKey: publicKeyOptionsFromServer(options.publicKey, rpId),
      signal,
    });
    if (!credential) throw new Error("Passkey enrollment was cancelled.");
    const verified = await post(
      API_PATHS.registrationVerify,
      { credential: serializeWebAuthnCredential(credential) },
      signal,
    );
    if (verified.status !== "REGISTERED") throw new Error("Passkey enrollment was not verified.");
    return { status: "REGISTERED" };
  }

  async function signIn({ signal } = {}) {
    requireTopLevelWindow();
    if (typeof credentialsApi.get !== "function") throw new Error("Passkey sign-in is unavailable.");
    const options = await post(API_PATHS.assertionOptions, {}, signal);
    const credential = await credentialsApi.get({
      publicKey: publicKeyOptionsFromServer(options.publicKey, rpId),
      signal,
    });
    if (!credential) throw new Error("Passkey sign-in was cancelled.");
    const verified = await post(
      API_PATHS.assertionVerify,
      { credential: serializeWebAuthnCredential(credential) },
      signal,
    );
    if (
      verified.status !== "VERIFIED" ||
      verified.handoffProofVersion !== 2 ||
      typeof verified.handoff !== "string"
    ) throw new Error("Passkey sign-in was not verified.");
    requireTopLevelWindow();
    submitHandoff(validateHandoff(verified.handoff), globalThis.document,
      `${identityConfig.receiverOrigin}/auth/consume`);
    return { status: "VERIFIED" };
  }

  return Object.freeze({ register, signIn });
}

function validPublicIdentityConfig(config, currentOrigin) {
  if (
    !config ||
    !["production", "staging"].includes(config.mode) ||
    config.handoffProofVersion !== 2 ||
    typeof config.frontendOrigin !== "string" ||
    typeof config.identityIssuerOrigin !== "string" ||
    typeof config.receiverOrigin !== "string" ||
    typeof config.webauthnRpId !== "string" ||
    config.frontendOrigin !== currentOrigin ||
    config.identityIssuerOrigin !== currentOrigin ||
    config.receiverOrigin === currentOrigin ||
    config.webauthnRpId.includes("*")
  ) return false;
  if (config.mode === "production" && (
    currentOrigin !== COM_IDENTITY_ORIGIN ||
    config.frontendOrigin !== COM_IDENTITY_ORIGIN ||
    config.identityIssuerOrigin !== COM_IDENTITY_ORIGIN ||
    config.receiverOrigin !== AI_RECEIVER_ORIGIN ||
    config.webauthnRpId !== PRODUCTION_RP_ID
  )) return false;
  try {
    const current = new URL(currentOrigin);
    const issuer = new URL(config.identityIssuerOrigin);
    const receiver = new URL(config.receiverOrigin);
    const rpId = config.webauthnRpId;
    return current.protocol === "https:" &&
      current.origin === currentOrigin &&
      issuer.protocol === "https:" &&
      issuer.origin === config.identityIssuerOrigin &&
      issuer.origin === currentOrigin &&
      receiver.protocol === "https:" &&
      receiver.origin === config.receiverOrigin &&
      receiver.origin !== currentOrigin &&
      (issuer.hostname === rpId || issuer.hostname.endsWith(`.${rpId}`));
  } catch {
    return false;
  }
}

export async function initializeIdentityGate({
  documentRef = globalThis.document,
  locationRef = globalThis.location,
  credentialsApi = globalThis.navigator?.credentials,
  fetchImpl = globalThis.fetch,
} = {}) {
  if (!documentRef || !locationRef) return;
  const signInButton = documentRef.getElementById("btn-enter");
  const registerButton = documentRef.getElementById("btn-enroll");
  const cancelButton = documentRef.getElementById("btn-cancel");
  const status = documentRef.getElementById("gate-out");
  if (!signInButton || !registerButton || !cancelButton || !status) return;

  const setStatus = (message) => { status.textContent = message; };
  signInButton.disabled = true;
  registerButton.disabled = true;
  cancelButton.hidden = true;
  if (!isTopLevelWindow()) {
    setStatus("Passkey identity requires the top-level window. No identity request was sent.");
    return;
  }
  if (!fetchImpl || locationRef.protocol !== "https:") {
    setStatus("The identity service is unavailable in this context. No identity request was sent.");
    return;
  }
  if (!credentialsApi || typeof credentialsApi.get !== "function" ||
      typeof credentialsApi.create !== "function" || globalThis.isSecureContext === false) {
    setStatus("Passkeys are unavailable in this secure browser context. No identity request was sent.");
    return;
  }

  let identityConfig;
  try {
    const response = await fetchImpl("/auth/config", {
      method: "GET",
      credentials: "same-origin",
      cache: "no-store",
      redirect: "error",
      headers: { accept: "application/json" },
    });
    if (!response.ok) throw new Error("Identity configuration unavailable.");
    identityConfig = await response.json();
  } catch {
    setStatus("The identity service is not configured for this site. No session was issued.");
    return;
  }
  if (!validPublicIdentityConfig(identityConfig, locationRef.origin)) {
    setStatus("The identity service returned an invalid site configuration. No session was issued.");
    return;
  }

  let client;
  try {
    requireTopLevelWindow();
    client = createIdentityGateClient({
      fetchImpl,
      credentialsApi,
      origin: locationRef.origin,
      identityConfig,
    });
  } catch {
    signInButton.disabled = true;
    registerButton.disabled = true;
    setStatus("Passkey identity configuration is invalid. No identity request was sent.");
    return;
  }

  let activeController = null;
  signInButton.disabled = false;
  registerButton.disabled = false;
  async function run(action, waitingMessage) {
    if (activeController) return;
    const controller = new AbortController();
    activeController = controller;
    signInButton.disabled = true;
    registerButton.disabled = true;
    cancelButton.hidden = false;
    setStatus(waitingMessage);
    try {
      const result = await client[action]({ signal: controller.signal });
      if (action === "register" && result?.status === "REGISTERED") {
        setStatus("Passkey created. Sign in to continue to the protected world.");
      }
    } catch (error) {
      setStatus(error?.name === "AbortError"
        ? "Canceled. The one-time challenge expires automatically; no session was issued."
        : "The identity check did not complete. No session was issued; try again when the gate is available.");
    } finally {
      if (activeController === controller) activeController = null;
      signInButton.disabled = false;
      registerButton.disabled = false;
      cancelButton.hidden = true;
    }
  }

  signInButton.addEventListener("click", () =>
    run("signIn", "Waiting for your passkey…"));
  registerButton.addEventListener("click", () =>
    run("register", "Creating a passkey on this device…"));
  cancelButton.addEventListener("click", () => activeController?.abort());
  cancelButton.hidden = true;
}

if (typeof document !== "undefined") initializeIdentityGate();
